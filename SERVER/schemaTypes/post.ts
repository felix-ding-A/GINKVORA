// schemaTypes/post.ts — Blog post schema
import { defineType, defineField, defineArrayMember } from 'sanity'
import { CustomMarkdownInput } from './components/CustomMarkdownInput'

export const postType = defineType({
  name: 'post',
  title: 'Blog Post',
  type: 'document',
  icon: () => '📝',
  groups: [
    { name: 'basic', title: 'Basic Info', default: true },
    { name: 'i18n', title: '🌍 Translations (RU)' },
    { name: 'seo', title: 'SEO Settings' },
    { name: 'faq', title: 'FAQ' },
  ],
  fields: [
    defineField({
      name: 'title',
      title: 'Title',
      type: 'string',
      group: 'basic',
      validation: (Rule) => Rule.required().max(100),
    }),
    defineField({
      name: 'slug',
      title: 'Slug',
      type: 'slug',
      group: 'basic',
      options: { source: 'title' },
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'author',
      title: 'Author',
      type: 'reference',
      to: [{ type: 'author' }],
      group: 'basic',
    }),
    defineField({
      name: 'coverImage',
      title: 'Cover Image',
      type: 'image',
      group: 'basic',
      options: { hotspot: true },
      fields: [
        defineField({ name: 'alt', type: 'string', title: 'Alt Text' }),
      ],
    }),
    defineField({
      name: 'publishedAt',
      title: 'Published At',
      type: 'datetime',
      group: 'basic',
      initialValue: () => new Date().toISOString(),
    }),
    defineField({
      name: 'updatedAt',
      title: 'Updated At (dateModified)',
      type: 'datetime',
      group: 'basic',
      description: 'Last update time of this post for schema.org dateModified.',
    }),
    defineField({
      name: 'excerpt',
      title: 'Excerpt',
      type: 'text',
      group: 'basic',
      rows: 3,
      description: 'Short summary shown in listing cards',
      validation: (Rule) => Rule.max(250),
    }),
    defineField({
      name: 'readTime',
      title: 'Read Time (minutes)',
      type: 'number',
      group: 'basic',
    }),
    defineField({
      name: 'tags',
      title: 'Tags',
      type: 'array',
      group: 'basic',
      of: [defineArrayMember({ type: 'string' })],
      options: {
        list: [
          { title: 'Industry News', value: 'Industry News' },
          { title: 'Ingredient Spotlight', value: 'Ingredient Spotlight' },
          { title: 'Research', value: 'Research' },
          { title: 'Regulatory', value: 'Regulatory' },
          { title: 'Market Trends', value: 'Market Trends' },
          { title: 'Quality & Testing', value: 'Quality & Testing' },
          { title: 'Formulation Tips', value: 'Formulation Tips' },
        ],
      },
    }),
    defineField({
      name: 'featured',
      title: 'Recommend on Homepage',
      type: 'boolean',
      group: 'basic',
      initialValue: false,
      description: 'If checked, this post will be featured in the Industry Insights section on the homepage.',
    }),
    defineField({
      name: 'body',
      title: 'Body (Markdown)',
      type: 'markdown',
      group: 'basic',
      components: {
        input: CustomMarkdownInput,
      },
    }),

    // ── 🌍 Translations (Russian) ─────────────────
    defineField({
      name: 'title_ru',
      title: '🇷🇺 Заголовок (RU)',
      type: 'string',
      group: 'i18n',
      description: 'Заголовок статьи на русском языке',
      validation: (Rule) => Rule.max(100),
    }),
    defineField({
      name: 'excerpt_ru',
      title: '🇷🇺 Краткое содержание (RU)',
      type: 'text',
      group: 'i18n',
      rows: 3,
      description: 'Краткое содержание статьи на русском языке (для карточек)',
      validation: (Rule) => Rule.max(250),
    }),
    defineField({
      name: 'body_ru',
      title: '🇷🇺 Текст статьи (RU, Markdown)',
      type: 'markdown',
      group: 'i18n',
      description: 'Полный текст статьи на русском языке.',
      components: { input: CustomMarkdownInput },
    }),
    defineField({
      name: 'seoTitle_ru',
      title: '🇷🇺 SEO Title (RU)',
      type: 'string',
      group: 'i18n',
      description: 'Заголовок страницы для поисковых систем на русском языке (до 60 символов).',
      validation: (Rule) => Rule.max(70),
    }),
    defineField({
      name: 'seoDescription_ru',
      title: '🇷🇺 SEO Description (RU)',
      type: 'text',
      group: 'i18n',
      rows: 3,
      description: 'Мета-описание для поисковых систем на русском языке (до 160 символов).',
      validation: (Rule) => Rule.max(160),
    }),

    defineField({
      name: 'seo',
      title: 'SEO',
      type: 'object',
      group: 'seo',
      fields: [
        defineField({ name: 'title', type: 'string', title: 'Meta Title' }),
        defineField({ name: 'description', type: 'text', title: 'Meta Description', rows: 3 }),
      ],
    }),
    defineField({
      name: 'seoTitle',
      title: 'SEO Title (Title Tag)',
      type: 'string',
      group: 'seo',
      description: 'Used for the browser title tag. Keep it under 60 characters.',
      validation: (Rule) => Rule.max(70),
    }),
    defineField({
      name: 'seoDescription',
      title: 'SEO Description (Meta Description)',
      type: 'text',
      group: 'seo',
      rows: 3,
      description: 'Used for the search engine results snippet. Keep it under 160 characters.',
      validation: (Rule) => Rule.max(160),
    }),
    defineField({
      name: 'faqItems',
      title: 'FAQ Items',
      type: 'array',
      group: 'faq',
      description: 'Add Frequently Asked Questions for this post (SEO-optimized)',
      of: [
        defineArrayMember({
          type: 'object',
          name: 'faqItem',
          title: 'FAQ Item',
          fields: [
            defineField({
              name: 'question',
              title: 'Question',
              type: 'string',
              validation: (Rule) => Rule.required(),
            }),
            defineField({
              name: 'answer',
              title: 'Answer',
              type: 'text',
              rows: 3,
              validation: (Rule) => Rule.required(),
            }),
          ],
        }),
      ],
    }),
    defineField({
      name: 'relatedProduct',
      title: 'Related Product',
      type: 'reference',
      to: [{ type: 'product' }],
      group: 'basic',
      description: 'Link this post to a related product (e.g. Quercetin product page)',
    }),
  ],
  orderings: [
    { title: 'Published Date (newest)', name: 'publishedAtDesc', by: [{ field: 'publishedAt', direction: 'desc' }] },
    { title: 'Published Date (oldest)', name: 'publishedAtAsc', by: [{ field: 'publishedAt', direction: 'asc' }] },
    { title: 'Author Name (A-Z)', name: 'authorNameAsc', by: [{ field: 'author.name', direction: 'asc' }] },
    { title: 'Author Name (Z-A)', name: 'authorNameDesc', by: [{ field: 'author.name', direction: 'desc' }] },
    { title: 'Title (A-Z)', name: 'titleAsc', by: [{ field: 'title', direction: 'asc' }] },
  ],
  preview: {
    select: { title: 'title', media: 'coverImage', date: 'publishedAt' },
    prepare({ title, media, date }) {
      return {
        title,
        subtitle: date ? new Date(date).toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' }) : 'No date',
        media,
      }
    },
  },
})
